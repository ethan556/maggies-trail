/** Generates src/components/figureIds.ts — the synchronous existence set for
 * the lazily-loaded figure library. Keeping the id set in its own tiny module
 * lets the player gate "does this figure exist?" without pulling the 26.9k-line
 * figures chunk into the route bundle. Drift is guarded by figures.split.test.ts. */
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync("src/components/figures.tsx", "utf8");
const start = src.indexOf("export const FIGURES");
const body = src.slice(start);
const monolithIds = [...body.matchAll(/^  "([A-Za-z0-9_-]+)": [A-Za-z0-9_]+,?$/gm)].map((m) => m[1]);
const modularSources = [
  "src/components/figures/howManyFigures.tsx",
  "src/components/figures/numberWritingFigures.tsx",
];
const modularIds = modularSources.flatMap((file) => {
  const moduleSource = readFileSync(file, "utf8");
  return [...moduleSource.matchAll(/^  "([A-Za-z0-9_-]+)": \{/gm)].map((match) => match[1]);
});
const ids = [...new Set([...modularIds, ...monolithIds])];
if (ids.length < 50) throw new Error(`suspiciously few figure ids parsed: ${ids.length}`);
const out = `// GENERATED by scripts/gen-figure-ids.mjs — do not edit by hand.
// Synchronous existence set for the lazily-loaded figure library (see FigureView).
export const FIGURE_IDS: ReadonlySet<string> = new Set(${JSON.stringify(ids, null, 0)});
`;
writeFileSync("src/components/figureIds.ts", out);
console.log(`figureIds.ts written: ${ids.length} ids`);
